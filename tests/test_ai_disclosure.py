def test_manifest_shape():
    definition = manifest_definition(ai_generated_manifest(sample_ai()), [])
    assert definition["claim_generator_info"][0]["name"] == "SSL Provenance API"
    assert len(definition["assertions"]) == 1
    actions_assertion = definition["assertions"][0]
    assert actions_assertion["label"] == "c2pa.actions"
    assert actions_assertion["created"] is True
    assert actions_assertion["data"]["allActionsIncluded"] is True
    assert actions_assertion["data"]["actions"] == [
        {
            "action": "c2pa.created",
            "when": "2026-10-13T09:30:00Z",
            "digitalSourceType": TRAINED_ALGORITHMIC_MEDIA,
            "softwareAgent": SAMPLE_AGENT,
            "description": SAMPLE_DESCRIPTION,
        }
    ]


def test_manifest_appends_custom_assertions():
    custom = {"label": "com.example.tracking", "data": {"internal_id": "abc"}}
    definition = manifest_definition(ai_generated_manifest(sample_ai()), [custom])
    assert [a["label"] for a in definition["assertions"]] == ["c2pa.actions", "com.example.tracking"]


