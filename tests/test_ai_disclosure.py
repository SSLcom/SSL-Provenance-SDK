"""AI-generated asset declaration (c2pa.created + digitalSourceType + softwareAgent).

Covers input validation, manifest shape and end-to-end signing through c2pa
against the fake CSC API.
"""

import datetime
import io
import json

import c2pa
import pytest

from conftest import CSC_ENDPOINT, TOKEN
from ssl_provenance_sdk import (
    TRAINED_ALGORITHMIC_MEDIA,
    AiDisclosure,
    AiDisclosureUnsupportedError,
    InvalidAiDisclosureError,
    ProvenanceClient,
    SignRequest,
)
from ssl_provenance_sdk.ai_disclosure import MAX_SOFTWARE_AGENT_EXTENSIONS, MAX_TSTR_LENGTH
from ssl_provenance_sdk.manifest import ai_generated_manifest, manifest_definition
from test_signing import _active, _failures, _read

NOW = datetime.datetime(2026, 10, 13, 9, 30, tzinfo=datetime.timezone.utc)

SAMPLE_AGENT = {
    "name": "Acme Image Generator",
    "version": "3.1",
    "com.ssl.modelIdentifier": "acme-imagegen-3.1-xl",
    "com.example.checkpoint": "2026-09-30",
}
SAMPLE_DESCRIPTION = "Generated by Acme Image Generator from a text prompt"


def sample_ai() -> AiDisclosure:
    return AiDisclosure.create(SAMPLE_AGENT, SAMPLE_DESCRIPTION).resolved(NOW)


# -- validation -------------------------------------------------------------------


def test_name_only_defaults_description_and_when():
    ai = AiDisclosure.create("Acme").resolved(NOW)
    assert ai.software_agent == {"name": "Acme"}
    assert ai.description == "Generated by Acme"
    assert ai.when == "2026-10-13T09:30:00Z"
    assert AiDisclosure.create({"name": "Acme"}) == AiDisclosure.create("Acme")


def test_preserves_multiple_extensions_verbatim():
    ai = sample_ai()
    assert ai.software_agent == SAMPLE_AGENT
    assert ai.description == SAMPLE_DESCRIPTION


@pytest.mark.parametrize(
    "when, expected",
    [
        ("2026-10-01T12:00:00+02:00", "2026-10-01T10:00:00Z"),
        ("2026-10-01T10:00:00z", "2026-10-01T10:00:00Z"),
        ("2026-10-01 10:00:00.5Z", "2026-10-01T10:00:00.500Z"),
        (datetime.datetime(2026, 10, 1, 7, tzinfo=datetime.timezone(datetime.timedelta(hours=-3))), "2026-10-01T10:00:00Z"),
    ],
)
def test_normalizes_caller_when_to_utc(when, expected):
    ai = AiDisclosure.create("Acme", when=when)
    assert ai.when == expected
    assert ai.resolved(NOW).when == expected  # a caller's time is kept


def _too_many_extensions():
    agent = {"name": "Acme"}
    agent.update({f"com.example.k{i}": "v" for i in range(MAX_SOFTWARE_AGENT_EXTENSIONS + 1)})
    return agent


TOO_LONG = "a" * (MAX_TSTR_LENGTH + 1)


@pytest.mark.parametrize(
    "agent, kwargs",
    [
        ({"version": "1"}, {}),  # missing name
        ({"name": "  "}, {}),  # blank name
        ({"name": 42}, {}),  # non-string name
        ({"name": "Acme", "version": ""}, {}),  # blank version
        ({"name": "Acme", "modelIdentifier": "x"}, {}),  # non-namespaced key
        ({"name": "Acme", "icon": "x"}, {}),  # standard-but-unsupported key
        ({"name": "Acme", "c2pa.model": "x"}, {}),  # reserved namespace
        ({"name": "Acme", "CAWG.model": "x"}, {}),  # reserved namespace, any case
        ({"name": "Acme", "com..model": "x"}, {}),  # empty segment
        ({"name": "Acme", "com.example.-x": "x"}, {}),  # bad segment start
        ({"name": "Acme", "com.ssl.modelIdentifier": 7}, {}),  # non-string extension
        ({"name": "Acme", "com.ssl.modelIdentifier": ""}, {}),  # blank extension
        (_too_many_extensions(), {}),
        ({"name": TOO_LONG}, {}),  # oversized name
        ({"name": "Acme", "com.ssl.modelIdentifier": TOO_LONG}, {}),  # oversized extension
        ({"name": "a" * MAX_TSTR_LENGTH}, {}),  # defaulted description too long
        ({"name": "Acme"}, {"description": " "}),  # blank description
        ({"name": "Acme"}, {"when": "yesterday"}),
        ({"name": "Acme"}, {"when": "2026-10-01"}),  # date only
        ({"name": "Acme"}, {"when": "2026-10-01T10:00:00"}),  # no offset
        ({"name": "Acme"}, {"when": datetime.datetime(2026, 10, 1)}),  # naive datetime
        ("", {}),  # blank name shorthand
    ],
)
def test_rejects_invalid_input(agent, kwargs):
    with pytest.raises(InvalidAiDisclosureError) as excinfo:
        AiDisclosure.create(agent, **kwargs)
    assert excinfo.value.status_code == 400


def test_accepts_max_length_strings_and_max_extensions():
    agent = {"name": "a" * MAX_TSTR_LENGTH}
    agent.update({f"com.example.k{i}": "v" for i in range(MAX_SOFTWARE_AGENT_EXTENSIONS)})
    AiDisclosure.create(agent, description="x")


def test_string_limit_counts_utf8_bytes():
    with pytest.raises(InvalidAiDisclosureError):
        AiDisclosure.create("é" * (MAX_TSTR_LENGTH // 2 + 1), description="x")


def test_from_dict_matches_http_service_shape():
    ai = AiDisclosure.from_dict(
        {"softwareAgent": SAMPLE_AGENT, "description": SAMPLE_DESCRIPTION, "when": "2026-10-13T09:30:00Z"}
    )
    assert ai == sample_ai()
    for bad in (
        {"softwareAgent": {"version": "1"}},
        {"softwareAgent": "Acme"},
        {"description": "x"},
        {"softwareAgent": {"name": "Acme"}, "digitalSourceType": "x"},  # unknown field
        {"softwareAgent": {"name": "Acme"}, "when": 5},
        [],
    ):
        with pytest.raises(InvalidAiDisclosureError):
            AiDisclosure.from_dict(bad)


def test_sign_request_setter():
    req = SignRequest().set_ai_disclosure(SAMPLE_AGENT, SAMPLE_DESCRIPTION, "2026-10-13T09:30:00Z")
    assert req.ai_disclosure == sample_ai()
    assert SignRequest().set_ai_disclosure(sample_ai()).ai_disclosure == sample_ai()
    assert req.set_ai_disclosure(None).ai_disclosure is None
    with pytest.raises(InvalidAiDisclosureError):
        SignRequest().set_ai_disclosure({"version": "1"})


def test_when_defaults_to_time_of_signing():
    req = (
        SignRequest()
        .set_c2pa_certificate_id("c")
        .set_content_type("image/png")
        .set_ai_disclosure("Acme")
    )
    assert req.ai_disclosure.when is None
    before = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)
    when = req.validate().ai_disclosure.when
    after = datetime.datetime.now(datetime.timezone.utc)
    parsed = datetime.datetime.fromisoformat(when.replace("Z", "+00:00"))
    assert before <= parsed <= after


