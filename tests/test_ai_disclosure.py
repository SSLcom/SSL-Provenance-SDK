@pytest.fixture()
def client(csc, pki):
    return (
        ProvenanceClient(trust_anchors=pki["anchors"])
        .set_csc_endpoint(CSC_ENDPOINT)
        .set_tsa_url(None)
        .set_session(csc)
    )


def _request(client, content_type, asset):
    return (
        client.new_request()
        .set_access_token(TOKEN)
        .set_c2pa_certificate_id("claim-cred")
        .set_content_type(content_type)
        .set_asset(asset)
    )


def _claim(pki, fmt, data, manifest_data=None):
    from ssl_provenance_sdk.manifest import build_c2pa_settings_json

    ctx = c2pa.Context(c2pa.Settings.from_json(build_c2pa_settings_json(pki["anchors"])))
    reader = c2pa.Reader(fmt, io.BytesIO(data), manifest_data, context=ctx)
    try:
        detailed = json.loads(reader.detailed_json())
    finally:
        reader.close()
    return detailed["manifests"][detailed["active_manifest"]]


def _created_action(manifest):
    labels = {a["label"]: a for a in manifest["assertions"]}
    data = labels["c2pa.actions.v2"]["data"]
    assert data["allActionsIncluded"] is True
    assert len(data["actions"]) == 1, "c2pa.created must be the only action"
    return data["actions"][0]


def test_e2e_png_declares_created_action(client, pki, png_bytes):
    signed = (
        _request(client, "image/png", png_bytes)
        .add_custom_assertion("com.example.tracking", {"internal_id": "abc"}, created=True)
        .set_ai_disclosure(SAMPLE_AGENT, SAMPLE_DESCRIPTION, "2026-10-13T09:30:00Z")
        .sign()
    )
    store = _read(pki, "image/png", signed)
    assert _failures(store) == []
    assert store["validation_state"] == "Trusted"

    manifest = _active(store)
    # No parentOf ingredient: the asset is the AI output itself.
    assert manifest.get("ingredients", []) == []
    # The claim generator is still the SDK, distinct from the AI tool.
    assert manifest["claim_generator_info"][0]["name"] == "SSL Provenance API"

    action = _created_action(manifest)
    assert action["action"] == "c2pa.created"
    assert action["digitalSourceType"] == TRAINED_ALGORITHMIC_MEDIA
    assert action["when"] == "2026-10-13T09:30:00Z"
    assert action["description"] == SAMPLE_DESCRIPTION
    assert action["softwareAgent"] == SAMPLE_AGENT  # every extension key survives

    claim = _claim(pki, "image/png", signed)["claim"]
    assert claim["claim_version"] == 2  # claims v2, as required for C2PA 2.2
    created = [a["url"] for a in claim["created_assertions"]]
    assert any(u.endswith("/c2pa.actions.v2") for u in created), created
    assert any(u.endswith("/com.example.tracking") for u in created), created
    assert not claim.get("gathered_assertions"), "nothing should be gathered"


def test_e2e_with_only_required_name(client, pki, png_bytes):
    signed = _request(client, "image/png", png_bytes).set_ai_disclosure("Acme Image Generator").sign()
    store = _read(pki, "image/png", signed)
    assert _failures(store) == []
    action = _created_action(_active(store))
    assert action["softwareAgent"] == {"name": "Acme Image Generator"}
    assert action["description"] == "Generated by Acme Image Generator"
    assert action["when"].endswith("Z")


def test_e2e_with_cawg_identity(client, pki, png_bytes):
    signed = (
        _request(client, "image/png", png_bytes)
        .set_cawg_certificate_id("identity-cred")
        .add_cawg_role("cawg.creator")
        .set_ai_disclosure("Acme Image Generator")
        .sign()
    )
    store = _read(pki, "image/png", signed)
    assert _failures(store) == []
    manifest = _active(store)
    assert _created_action(manifest)["digitalSourceType"] == TRAINED_ALGORITHMIC_MEDIA
    assert any(a["label"].startswith("cawg.identity") for a in manifest["assertions"])


def test_e2e_pdf_sidecar(client, pki, pdf_bytes):
    sidecar = _request(client, "application/pdf", pdf_bytes).set_ai_disclosure("Acme Writer").sign()
    store = _read(pki, "application/pdf", pdf_bytes, manifest_data=sidecar)
    manifest = _active(store)
    assert manifest.get("ingredients", []) == []
    assert _created_action(manifest)["softwareAgent"] == {"name": "Acme Writer"}


def test_e2e_rejected_for_asset_with_existing_manifest(client, png_bytes):
    signed_once = _request(client, "image/png", png_bytes).sign()
    with pytest.raises(AiDisclosureUnsupportedError) as excinfo:
        _request(client, "image/png", signed_once).set_ai_disclosure("Acme").sign()
    assert excinfo.value.status_code == 422
    assert "already carries Content Credentials" in str(excinfo.value)
