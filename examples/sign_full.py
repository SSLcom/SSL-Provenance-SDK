"""Sign an asset with a C2PA manifest with all options using the SSL.com Provenance API.

Usage:
    python examples/sign_full.py

Edit the values at the top of main() first; nothing is read from the
environment.
"""

import logging
import sys
from pathlib import Path

from ssl_provenance_sdk import (
    ProvenanceClient,
    ProvenanceError,
    download_trust_anchors,
    get_access_token,
)

HERE = Path(__file__).parent


def main() -> int:
    # "sandbox" (testing) or "production": selects the OAuth, CSC and TSA
    # endpoints. The account and credential IDs must belong to the same
    # environment.
    environment = "production"
    username = "YOUR_ESIGNER_USERNAME"
    password = "YOUR_ESIGNER_PASSWORD"
    client_id = "YOUR_OAUTH_CLIENT_ID"
    client_secret = "YOUR_OAUTH_CLIENT_SECRET"
    # SSL.com C2PA timestamping authority token,
    # applies to every request; request.set_tsa_token() overrides it for one.
    tsa_token = "YOUR_TSA_TOKEN"
    credential_id = "983da863-ce7f-42b5-b227-c9076c7b34af" # default SSL Provenance API C2PA certificate
    content_type = "image/jpeg"
    unsigned_asset_path = HERE / "sample.jpg"
    signed_asset_path = HERE / "signed.jpg"
    trust_list_url = (
        "https://raw.githubusercontent.com/c2pa-org/conformance-public/main/"
        "trust-list/C2PA-TRUST-LIST.pem"
    )
    tsa_trust_list_url = (
        "https://raw.githubusercontent.com/c2pa-org/conformance-public/main/"
        "trust-list/C2PA-TSA-TRUST-LIST.pem"
    )
    # Optional: a credential that signs a CAWG identity assertion naming the
    # creator, e.g. "YOUR_CAWG_CREDENTIAL_ID". Empty to leave it out.
    cawg_credential_id = ""
    # Declares the asset as AI-generated (c2pa.created +
    # trainedAlgorithmicMedia), naming the AI tool: "name" is required,
    # "version" and namespaced extension keys are optional. A plain string
    # such as "Acme Image Generator" is shorthand for {"name": ...}. Set to
    # None for assets that aren't AI-generated or already carry a manifest.
    ai_software_agent = {
        "name": "Acme Image Generator",
        "version": "3.1",
        "com.ssl.modelIdentifier": "acme-imagegen-3.1-xl",
    }
    # Optional; defaults to "Generated by <name>".
    ai_description = "Generated by Acme Image Generator from a text prompt"

    logging.basicConfig(level=logging.INFO)

    client = ProvenanceClient(environment, tsa_token=tsa_token)
    # Individual endpoints can still be overridden, e.g.:
    #   client.set_csc_endpoint("https://cs-try.ssl.com")
    #   client.set_tsa_url("https://ts-c2pa.ssl.com/ecc")

    # Get an access token. It lasts about an hour; a long-running service would
    # call refresh_access_token(token.refresh_token, client_id, client_secret,
    # client.oauth_token_url) before token.expires_within(60) becomes true,
    # instead of logging in again.
    try:
        token = get_access_token(
            username, password, client_id, client_secret, client.oauth_token_url
        )
    except ProvenanceError as e:
        print(f"could not get an access token ({e.status_code}): {e}", file=sys.stderr)
        return 1

    # Download and merge the trust lists once and keep the result in memory.
    # Every client gets the same string; signing never downloads anything.
    try:
        trust_anchors = download_trust_anchors(trust_list_url, tsa_trust_list_url)
    except ProvenanceError as e:
        # Signing still works; existing credentials just can't be validated
        # as trusted.
        logging.warning("continuing without trust anchors: %s", e)
        trust_anchors = None

    client.set_trust_anchors(trust_anchors)

    # Any other client shares the same in-memory trust anchors, e.g.:
    #   production = ProvenanceClient("production", trust_anchors=trust_anchors)

    request = (
        client.new_request()
        .set_access_token(token)
        .set_c2pa_certificate_id(credential_id)
        .set_content_type(content_type)
        .set_asset(unsigned_asset_path.read_bytes())
        .add_custom_assertion(
            "com.example.review", {"reviewer": "jane", "rating": 5}
        )
    )

    if ai_software_agent:
        # "when" is left out, so it defaults to the time of signing.
        request.set_ai_disclosure(ai_software_agent, description=ai_description)

    if cawg_credential_id:
        request.set_cawg_certificate_id(cawg_credential_id).add_cawg_role("cawg.creator")

    try:
        signed = request.sign()
    except ProvenanceError as e:
        print(f"signing failed ({e.status_code}): {e}", file=sys.stderr)
        return 1

    signed_asset_path.write_bytes(signed)
    kind = "sidecar manifest" if content_type == "application/pdf" else "signed asset"
    print(f"wrote {kind} ({len(signed)} bytes) to {signed_asset_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
