"""Declaring an asset as AI-generated.

Accepts the same ``ai_disclosure`` input, with the same validation, as the
SSL.com Provenance API. An AI disclosure makes the manifest declare
the asset with the standard C2PA 2.2 creation declaration: a single
``c2pa.created`` action with ``digitalSourceType``
:data:`TRAINED_ALGORITHMIC_MEDIA`, a ``softwareAgent`` naming the AI tool, a
``description`` and ``when``, plus ``allActionsIncluded: true``, and no
``parentOf`` ingredient (the asset *is* the AI output, not an ingredient of
it). See :func:`~ssl_provenance_sdk.manifest.ai_generated_manifest`.

The values are signer-asserted: the SDK embeds and signs them but cannot check
how the asset was produced. For assets generated outside your own pipeline,
you are responsible for their accuracy.
"""

from __future__ import annotations

import datetime as _dt
import re
from dataclasses import dataclass, field
from typing import Any, Dict, Mapping, Optional, Union

from .errors import InvalidAiDisclosureError

#: IPTC digital source type for "digital media created algorithmically using a
#: model derived from sampled content", i.e. generative AI output.
TRAINED_ALGORITHMIC_MEDIA = (
    "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
)

#: C2PA ``max-tstr-length``: the maximum size, in UTF-8 bytes, of a text string
#: in a C2PA data structure. Applied to every AI disclosure string, including
#: the generated default ``description``.
MAX_TSTR_LENGTH = 65_535

#: Maximum number of namespaced extension keys in ``softwareAgent``.
MAX_SOFTWARE_AGENT_EXTENSIONS = 16

#: Maximum length of a ``softwareAgent`` extension key.
MAX_EXTENSION_KEY_LENGTH = 256

_SEGMENT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")
_RFC3339 = re.compile(
    r"^\d{4}-\d{2}-\d{2}[Tt ]\d{2}:\d{2}:\d{2}(\.\d+)?([Zz]|[+-]\d{2}:\d{2})$"
)

#: Keys accepted by :meth:`AiDisclosure.from_dict` (the HTTP service's
#: ``manifest_options.ai_disclosure`` object).
_DICT_KEYS = {"softwareAgent", "description", "when"}


@dataclass(frozen=True)
class AiDisclosure:
    """A validated AI disclosure.

    ``when`` is a normalized RFC 3339 UTC timestamp, or ``None`` to use the
    time of signing (resolved by :meth:`resolved`).
    """

    software_agent: Dict[str, str] = field(default_factory=dict)
    description: str = ""
    when: Optional[str] = None

    @classmethod
    def create(
        cls,
        software_agent: Union[str, Mapping[str, Any]],
        description: Optional[str] = None,
        when: Union[str, _dt.datetime, None] = None,
    ) -> "AiDisclosure":
        """Validate the inputs and build an :class:`AiDisclosure`.

        ``software_agent`` is the AI tool as a C2PA ``generator-info-map``:
        ``name`` (required), optional ``version``, plus up to
        :data:`MAX_SOFTWARE_AGENT_EXTENSIONS` namespaced extension keys such as
        ``com.ssl.modelIdentifier``. A plain string is shorthand for
        ``{"name": software_agent}``. ``description`` defaults to
        ``"Generated by <name>"``. ``when`` (an RFC 3339 string or a
        timezone-aware ``datetime``) defaults to the time of signing.

        Raises :class:`InvalidAiDisclosureError` naming the first problem.
        """
        if isinstance(software_agent, str):
            software_agent = {"name": software_agent}
        agent = _validate_software_agent(software_agent)

        if description is None:
            description = f"Generated by {agent['name']}"
        _validate_string("description", description)

        return cls(
            software_agent=agent,
            description=description,
            when=None if when is None else _normalize_when(when),
        )

    @classmethod
    def from_dict(cls, value: Mapping[str, Any]) -> "AiDisclosure":
        """Build from the HTTP service's ``ai_disclosure`` JSON object::

            {"softwareAgent": {"name": "...", "version": "..."},
             "description": "...", "when": "2026-10-01T10:00:00Z"}

        Unknown keys are rejected so a misspelled key fails loudly.
        """
        if not isinstance(value, Mapping):
            raise InvalidAiDisclosureError("ai_disclosure must be a JSON object")
        unknown = sorted(set(value) - _DICT_KEYS)
        if unknown:
            raise InvalidAiDisclosureError(
                f"unknown field(s) {', '.join(unknown)}; expected softwareAgent, "
                "description, when"
            )
        if "softwareAgent" not in value:
            raise InvalidAiDisclosureError("softwareAgent is required")
        agent = value["softwareAgent"]
        if not isinstance(agent, Mapping):
            raise InvalidAiDisclosureError("softwareAgent must be a JSON object")
        description = value.get("description")
        if description is not None and not isinstance(description, str):
            raise InvalidAiDisclosureError("description must be a string")
        when = value.get("when")
        if when is not None and not isinstance(when, str):
            raise InvalidAiDisclosureError("when must be a string")
        return cls.create(agent, description, when)

    def resolved(self, now: Optional[_dt.datetime] = None) -> "AiDisclosure":
        """This disclosure with ``when`` filled in (``now``, default the
        current time) if it was left unset."""
        if self.when is not None:
            return self
        now = now or _dt.datetime.now(_dt.timezone.utc)
        return AiDisclosure(
            software_agent=dict(self.software_agent),
            description=self.description,
            when=_format_utc(now.replace(microsecond=0)),
        )

    def to_action(self) -> dict:
        """The ``c2pa.created`` action this disclosure declares."""
        if self.when is None:
            raise ValueError("call resolved() first to fill in 'when'")
        return {
            "action": "c2pa.created",
            "when": self.when,
            "digitalSourceType": TRAINED_ALGORITHMIC_MEDIA,
            "softwareAgent": dict(self.software_agent),
            "description": self.description,
        }


def _validate_string(field_name: str, value: Any) -> None:
    if not isinstance(value, str):
        raise InvalidAiDisclosureError(f"{field_name} must be a string")
    if not value.strip():
        raise InvalidAiDisclosureError(f"{field_name} must not be empty")
    size = len(value.encode("utf-8"))
    if size > MAX_TSTR_LENGTH:
        raise InvalidAiDisclosureError(
            f"{field_name} exceeds the C2PA {MAX_TSTR_LENGTH}-byte string limit "
            f"({size} bytes)"
        )


def validate_extension_key(key: str) -> None:
    """Check a ``softwareAgent`` extension key: reverse-domain notation with at
    least two dot-separated segments (each starting with a letter or digit and
    containing only letters, digits, ``-`` or ``_``), outside the reserved
    ``c2pa``/``cawg`` namespaces. Same rules as the HTTP service's custom
    assertion labels."""
    if not key:
        raise ValueError("key must not be empty")
    if len(key) > MAX_EXTENSION_KEY_LENGTH:
        raise ValueError(f"key exceeds the {MAX_EXTENSION_KEY_LENGTH}-character limit")
    segments = key.split(".")
    if len(segments) < 2:
        raise ValueError(
            "key must use reverse-domain notation with at least two segments, "
            "e.g. com.example.my-key"
        )
    for segment in segments:
        if not _SEGMENT.match(segment):
            raise ValueError(
                f"segment {segment!r} is invalid: each dot-separated segment must "
                "start with a letter or digit and contain only letters, digits, '-', or '_'"
            )
    top_level = segments[0].lower()
    if top_level in ("c2pa", "cawg"):
        raise ValueError(f"key must not use the reserved {top_level!r} namespace")


def _validate_software_agent(agent: Mapping[str, Any]) -> Dict[str, str]:
    if not isinstance(agent, Mapping):
        raise InvalidAiDisclosureError("softwareAgent must be a name or a mapping")
    if "name" not in agent:
        raise InvalidAiDisclosureError("softwareAgent.name is required")
    _validate_string("softwareAgent.name", agent["name"])
    if "version" in agent:
        _validate_string("softwareAgent.version", agent["version"])

    extensions = 0
    for key, value in agent.items():
        if key in ("name", "version"):
            continue
        if not isinstance(key, str):
            raise InvalidAiDisclosureError("softwareAgent keys must be strings")
        try:
            validate_extension_key(key)
        except ValueError as e:
            raise InvalidAiDisclosureError(
                f"softwareAgent key {key!r} is not a namespaced extension key "
                f"(e.g. com.ssl.modelIdentifier): {e}"
            ) from None
        _validate_string(f"softwareAgent.{key}", value)
        extensions += 1
    if extensions > MAX_SOFTWARE_AGENT_EXTENSIONS:
        raise InvalidAiDisclosureError(
            f"softwareAgent exceeds the {MAX_SOFTWARE_AGENT_EXTENSIONS}-extension-key "
            f"limit ({extensions} keys)"
        )
    return dict(agent)


def _normalize_when(when: Union[str, _dt.datetime]) -> str:
    if isinstance(when, _dt.datetime):
        if when.tzinfo is None:
            raise InvalidAiDisclosureError("when must be a timezone-aware datetime")
        return _format_utc(when)
    if not isinstance(when, str):
        raise InvalidAiDisclosureError("when must be an RFC 3339 string or a datetime")
    text = when.strip()
    example = "e.g. 2026-10-13T09:30:00Z"
    if not _RFC3339.match(text):
        raise InvalidAiDisclosureError(f"when must be an RFC 3339 timestamp, {example}")
    iso = text[:-1] + "+00:00" if text[-1] in "Zz" else text
    iso = iso[:10] + "T" + iso[11:]
    # Python < 3.11 accepts at most 6 fractional digits.
    iso = re.sub(r"(\.\d{6})\d+", r"\1", iso)
    try:
        parsed = _dt.datetime.fromisoformat(iso)
    except ValueError as e:
        raise InvalidAiDisclosureError(f"when must be an RFC 3339 timestamp, {example}: {e}") from None
    return _format_utc(parsed)


def _format_utc(value: _dt.datetime) -> str:
    utc = value.astimezone(_dt.timezone.utc)
    if utc.microsecond == 0:
        spec = "seconds"
    elif utc.microsecond % 1000 == 0:
        spec = "milliseconds"
    else:
        spec = "microseconds"
    return utc.isoformat(timespec=spec).replace("+00:00", "Z")
